"""Rebuild recovery_change_manifest.json from the actual worktree. Zero physics."""
from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

EVIDENCE_REL = Path("docs/evidence/drecover001")
EXCLUDED_EXACT = {
    "docs/evidence/drecover001/recovery_change_manifest.json",
    "docs/evidence/drecover001/recovery_readiness.json",
    "docs/evidence/drecover001/recovery_readiness.md",
    "docs/evidence/drecover001/a5_review_packet.json",
    "docs/evidence/drecover001/a5_review_packet.md",
}
# The restore receipt is written only after a bundle exists, so it cannot be
# hashed into the bundle that it describes without creating a self-reference.
# It is excluded from the change manifest and reported explicitly instead.
GENERATED_AFTER_BUNDLE = {
    "docs/evidence/drecover001/local_restore_receipt.json":
        "generated by run_local_restore.py after the bundle exists; excluded from "
        "the bundle manifest to avoid a self-referential hash",
}


def git(root, args):
    out = subprocess.run(["git", "-C", str(root), *args], capture_output=True,
                         text=True, timeout=60)
    if out.returncode != 0:
        raise RuntimeError((out.stderr or out.stdout).strip()[:400])
    return out.stdout


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=str(Path(__file__).resolve().parents[3]))
    args = parser.parse_args(argv)
    root = Path(args.root).resolve()
    branch = git(root, ["rev-parse", "--abbrev-ref", "HEAD"]).strip()
    baseline = git(root, ["rev-parse", "HEAD"]).strip()
    status = git(root, ["status", "--porcelain=v1", "-z", "--untracked-files=all"])
    files, deleted = [], []
    for raw in status.split("\0"):
        if not raw:
            continue
        code = raw[:2]
        name = raw[3:]
        if " -> " in name:
            name = name.split(" -> ", 1)[1]
        if not name or "__pycache__/" in name or name.endswith(".pyc"):
            continue
        if name in EXCLUDED_EXACT or name in GENERATED_AFTER_BUNDLE:
            continue
        if "D" in code and code != "??":
            deleted.append(name)
            continue
        path = root / name
        if not path.is_file():
            deleted.append(name)
            continue
        data = path.read_bytes()
        state = ("untracked" if code == "??" else "added" if "A" in code
                 else "renamed" if "R" in code else "modified")
        files.append({"path": name, "status": state,
                      "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)})
    files.sort(key=lambda item: item["path"])
    worktree_clean = not files and not deleted
    manifest = {
        "schema": "drecover001.recovery_change_manifest.v1",
        "branch": branch,
        "baseline": baseline,
        "head": baseline,
        "worktree_clean": worktree_clean,
        "note": ("Working-tree changes relative to baseline (HEAD), regenerated from the actual "
                 "worktree by build_change_manifest.py. When the worktree is clean, files is empty "
                 "and worktree_clean is true with head recorded; snapshots are pushed through the "
                 "GitHub Data API because CLI git transport has no configured credential. Excludes "
                 "__pycache__/.pyc, this manifest, readiness aggregator outputs, generated A5 review "
                 "packet, and the post-bundle restore receipt (self-reference avoidance)."),
        "generated_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "file_count": len(files),
        "total_bytes": sum(item["bytes"] for item in files),
        "files": files,
        "deleted_pending_review": sorted(deleted),
        "generated_after_bundle_excluded": [
            {"path": name, "reason": reason}
            for name, reason in sorted(GENERATED_AFTER_BUNDLE.items())
        ],
        "self_excluded": True,
    }
    out = root / EVIDENCE_REL / "recovery_change_manifest.json"
    out.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps({"file_count": manifest["file_count"],
                      "total_bytes": manifest["total_bytes"],
                      "deleted": len(deleted)}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())