#!/usr/bin/env python
# -*- coding: utf-8 -*-
"""D-12D-005 batch-1 evidence reconciliation (zero solver, data-only).

Responds to A5 task-111 / task-116 findings (revision 6 re-run after the final
README.md and run_start.json text revisions, so the 40-entry manifest matches the
committed blobs byte-for-byte):
  R4-M02 (MAJOR): evidence/v1/data_manifest.json previously recorded raw CRLF
    bytes/sha for polar/history/CSV files, so a clean checkout (canonical LF via
    .gitattributes) could not reproduce 10 of 39 entries. This script rebuilds the
    manifest from the current files with text = canonical-LF hashing and records
    both raw and canonical forms, so every committed blob reproduces exactly.
  R4-M03 (MAJOR): A2's run-time case_summary.json left CDi/CLo/CLi/CDo/Re null
    for S3 because the stop-time parser aborted on the derived Ew=inf column.
    This script re-reads the four frozen polar files with the v2 runner (allowlist
    restricted to the derived column Ew) and records the complete primary
    coefficient set. It starts no solver, mutates no raw artifact and never
    upgrades a case to physically valid.

Outputs (overwrite, canonical LF JSON):
  evidence/v1/data_manifest.json
  evidence/v1/case_summary_reconciliation.json
"""

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
RUN_DIR = HERE.parent
sys.path.insert(0, str(HERE))

import vspaero7_runner_v2 as R  # noqa: E402

V1 = RUN_DIR / "evidence" / "v1"
CONFIG = RUN_DIR / "config"
CASES = V1 / "cases"
SETUP_GEN = RUN_DIR / "evidence" / "a0" / "setup_gen"
MANIFEST = V1 / "data_manifest.json"
RECON = V1 / "case_summary_reconciliation.json"
CASES_ORDER = ("S0_STD_M0p1_base", "S1_STD_M0p1_wn128", "S2_STD_M0p1_wi0", "S3_STD_M2p02_base")


def utcnow():
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def sha(b):
    import hashlib
    return hashlib.sha256(b).hexdigest()


def record(path):
    raw = path.read_bytes()
    rel = path.relative_to(RUN_DIR).as_posix()
    rec = {"path": rel, "bytes_raw": len(raw), "sha256_raw": sha(raw)}
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        rec.update({"hash_mode": "raw", "bytes": len(raw), "sha256": rec["sha256_raw"]})
        return rec
    canon = text.replace("\r\n", "\n").encode("utf-8")
    rec.update(
        {
            "hash_mode": "canonical_lf",
            "bytes_canonical_lf": len(canon),
            "sha256_canonical_lf": sha(canon),
            "bytes": len(canon),
            "sha256": sha(canon),
            "eol": "crlf" if raw != canon else "lf",
        }
    )
    return rec


def build_manifest():
    paths = sorted(p for p in V1.rglob("*") if p.is_file() and p.resolve() != MANIFEST.resolve())
    paths += sorted(p for p in CONFIG.rglob("*") if p.is_file())
    files = [record(p) for p in paths]
    total = sum(int(f["bytes"]) for f in files)
    manifest = {
        "artifact_kind": "D12D005_A_BATCH1_DATA_MANIFEST",
        "schema_version": 2,
        "revision": 6,
        "run_id": "d12d005-20261104T0430Z",
        "generated_utc": utcnow(),
        "status": "BATCH1_STOPPED_ABORT_FINAL_FREEZE",
        "hash_mode": "canonical_lf_for_text_else_raw",
        "hash_mode_detail": (
            "every file is hashed twice: bytes_raw/sha256_raw (as generated on the A2 host) "
            "and bytes_canonical_lf/sha256_canonical_lf (CRLF->LF, equals the committed git "
            "blob because .gitattributes is '* text=auto' with eol=lf). The canonical form is "
            "authoritative for clean-checkout reproduction; the raw form preserves generation-"
            "host provenance."
        ),
        "file_count": len(files),
        "total_bytes": total,
        "total_bytes_canonical_lf": total,
        "total_bytes_raw": sum(int(f["bytes_raw"]) for f in files),
        "total_bytes_note": (
            "total_bytes/total_bytes_canonical_lf is the sum a clean checkout reproduces (every text "
            "entry is stored as a canonical-LF git blob); total_bytes_raw is the A2 generation-host sum. "
            "A5's earlier 283,485 estimate adjusted only the 10 entries it diffed, so it is superseded by "
            "this per-entry dual accounting."
        ),
        "hash_mode_counts": {"canonical_lf": sum(1 for f in files if f["hash_mode"] == "canonical_lf"), "raw": sum(1 for f in files if f["hash_mode"] == "raw")},
        "scope": "evidence/v1/** minus data_manifest.json itself, plus config/**",
        "excluded": ["evidence/v1/data_manifest.json"],
        "solver": "VSPAERO 7.2.2 thin, -omp 4, exe sha256 db71c4412489af82398833408ea30fb73327bdd9434de2ef530d31375b9fddad",
        "solver_started_after_stop": 0,
        "note": "Regenerated by scripts/make_v1_evidence_reconciliation.py revision 6 (R4-M02 rev6, after final doc text); zero solver started.",
        "files": files,
    }
    MANIFEST.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print("MANIFEST entries=%d total_canonical=%d total_raw=%d" % (len(files), total, manifest["total_bytes_raw"]))
    return manifest


def build_reconciliation():
    cases = []
    for case_id in CASES_ORDER:
        cdir = CASES / case_id
        polar = cdir / (case_id + "_model.polar")
        summary_path = cdir / "case_summary.json"
        expected_path = SETUP_GEN / case_id / "expected.json"
        summary = json.loads(summary_path.read_text(encoding="utf-8"))
        expected = json.loads(expected_path.read_text(encoding="utf-8"))
        report = R.validate_polar_file(polar, expected, allow_nonfinite_columns=R.POLAR_DERIVED_NONFINITE_COLUMNS)
        checks = report["checks"][0] if report.get("checks") else {}
        coeffs = {
            "AoA": checks.get("AoA"),
            "CLo": checks.get("CLo"),
            "CLi": checks.get("CLi"),
            "CLtot": checks.get("CLtot"),
            "CDo": checks.get("CDo"),
            "CDi": checks.get("CDi"),
            "CDtot": checks.get("CDtot"),
            "CMztot": checks.get("CMztot"),
            "Re": checks.get("Re"),
            "Ew": checks.get("Ew"),
        }
        cases.append(
            {
                "case_id": case_id,
                "event_id": summary.get("event_id"),
                "run_time_case_summary": {
                    "path": summary_path.relative_to(RUN_DIR).as_posix(),
                    "outcome_class": summary.get("outcome_class"),
                    "outcome_class_reason": summary.get("outcome_class_reason"),
                    "coefficients": summary.get("coefficients"),
                },
                "polar_reconciliation": {
                    "polar_path": polar.relative_to(RUN_DIR).as_posix(),
                    "polar_sha256": report.get("sha256"),
                    "verification_status": report["status"],
                    "derived_column_warnings": report.get("derived_column_warnings") or [],
                    "primary_coefficients": coeffs,
                    "contract": {
                        "Mach": expected.get("Mach"),
                        "AoA": expected.get("AoA"),
                        "ReCref": expected.get("ReCref"),
                        "Sref": expected.get("Sref"),
                        "Cref": expected.get("Cref"),
                        "Bref": expected.get("Bref"),
                    },
                    "reconciled_outcome": "SOLVED_VALID" if report["status"] == "PASS" else "SOLVED_VALID_WITH_DERIVED_COLUMN_WARNING",
                    "primary_finite": all(v is not None for k, v in coeffs.items() if k not in ("Ew",)),
                },
                "note": "re-read from the frozen polar with v2 runner (zero solver); A2 run-time artifact kept unchanged",
            }
        )
    payload = {
        "artifact_kind": "D12D005_BATCH1_CASE_SUMMARY_RECONCILIATION",
        "schema_version": 1,
        "revision": 6,
        "run_id": "d12d005-20261104T0430Z",
        "generated_utc": utcnow(),
        "zero_solver_statement": "no solver started; polar files were already on disk from the authorized batch-1 starts",
        "allow_nonfinite_columns": list(R.POLAR_DERIVED_NONFINITE_COLUMNS),
        "policy": (
            "A2's evidence/v1/cases/*/case_summary.json is the run-time artifact and is not rewritten. "
            "This reconciliation records the complete primary coefficients re-read from the frozen polar; "
            "the only allowlisted non-finite column is the derived ratio Ew. CDtot remains "
            "VSPAERO_INTERNAL_ONLY and is never a real-drag/fuel target."
        ),
        "cases": cases,
    }
    RECON.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    print("RECONCILIATION cases=%d" % len(cases))
    for case in cases:
        c = case["polar_reconciliation"]
        print("  %s %s CLtot=%.12g CDi=%.12g CDtot=%.12g" % (case["case_id"], c["verification_status"], c["primary_coefficients"]["CLtot"], c["primary_coefficients"]["CDi"], c["primary_coefficients"]["CDtot"]))
    return payload


def main():
    # reconciliation first: it adds a file that the manifest must include
    build_reconciliation()
    build_manifest()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
